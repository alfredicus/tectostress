// The synthetic tectonic phases (examples): reproducible, read by the library as intended, and
// with the misfits announced. WRITE_SYNTHETIC=1 rewrites src/components/data/synthetic-phases.ts.

import * as fs from 'fs';
import * as path from 'path';
import { DataFactory } from '@alfredo-taboada/stress';
import { processCSV } from '../../../../io/CSVParsing';
import { engineOf, FRICTION } from '../generator';
import { buildSyntheticPhases, PHASES } from '../phases';

const FILE = path.join(__dirname, '../../synthetic-phases.ts');
const built = buildSyntheticPhases();

function source(): string {
    const examples = built.map(d => `        '${d.key}': {\n            name: '${d.name}',\n            csv: \`${d.csv}\`,\n        },`).join('\n');
    return `// Generated by src/components/data/synthetic (WRITE_SYNTHETIC=1 npx jest src/components/data/synthetic).
// Do not edit by hand. Ids: 1xx/2xx compression (a)/(b), 3xx/4xx extension, 5xx/6xx strike-slip.
// "Deformation phase": 1 compression, 2 extension, 3 strike-slip (the truth, for checking a separation).

export const synthetic_phases = {
    name: 'Synthetic tectonic phases',
    examples: {
${examples}
    },
};
`;
}

if (process.env.WRITE_SYNTHETIC) fs.writeFileSync(FILE, source());

const angleDeg = (a: number[], b: number[], oriented: boolean) => {
    const c = (a[0] * b[0] + a[1] * b[1] + a[2] * b[2]) / (Math.hypot(...a) * Math.hypot(...b));
    return Math.acos(Math.min(1, Math.max(-1, oriented ? c : Math.abs(c)))) * 180 / Math.PI;
};

/**
 * Misfit of each row with the stress state, as the app shows it (computePredictions): the angle
 * between the measured and the predicted striation, or plane normal. (The library's `cost` with
 * the ANGLE criterion is this angle divided by π.)
 */
function misfits(csv: string, phase: number): number[] {
    const engine = engineOf(PHASES[phase - 1].state);
    const stress = engine.stress([0, 0, 0]);
    return processCSV(csv).data.map((row: any) => {
        const d: any = DataFactory.create(row.type);
        d.initialize(row);
        const pred = d.predict(engine, { stress });
        return Array.isArray(pred) ? angleDeg(d.normal, pred, false) : angleDeg(d.striationVector ?? d.nStriation, pred.striation, true);
    });
}

test('the examples file is the generator output', () => {
    expect(fs.readFileSync(FILE, 'utf8')).toBe(source());
});

describe.each(built.map(d => [d.key, d] as const))('%s', (key, dataset) => {
    const phase = PHASES.find(p => key.startsWith(p.key))!.phase;
    const parsed = processCSV(dataset.csv);
    const cost = misfits(dataset.csv, phase);

    test('20 data: 16 striated faults, 2 tension fractures, 2 stylolites, phase column', () => {
        expect(parsed.data.map((r: any) => r.type.toLowerCase())).toEqual([
            ...Array(16).fill('striated plane'), 'extension fracture', 'extension fracture', 'stylolite interface', 'stylolite interface']);
        expect(parsed.data.every((r: any) => r.deformationPhase === phase || r['deformation phase'] === phase)).toBe(true);
    });

    test('measured to the degree', () => {
        parsed.data.forEach((r: any) => {
            expect(Number.isInteger(r.strike) && Number.isInteger(r.dip)).toBe(true);
            if (r.type.toLowerCase() === 'striated plane') expect(Number.isInteger(r.rake)).toBe(true);
        });
    });

    test('misfits as announced, and as the library computes them', () => {
        cost.forEach((c, i) => expect(Math.abs(c - dataset.rows[i].misfit)).toBeLessThan(0.01));
        if (key.endsWith('exact')) {
            // Only the rounding of the rake, strike and dip to whole degrees
            expect(Math.max(...cost)).toBeLessThan(1);
        } else {
            expect(Math.max(...cost)).toBeLessThan(20);
            expect(cost.filter(c => c < 8).length).toBeGreaterThanOrEqual(11);   // ~68 % within one σ
        }
    });

    test('12 faults in the reactivation zone, 4 just below it', () => {
        const ratios = dataset.rows.slice(0, 16).map(r => r.ratio!);
        expect(ratios.filter(r => r >= FRICTION)).toHaveLength(12);
        expect(ratios.filter(r => r < FRICTION && r >= 0.45)).toHaveLength(4);
    });
});

test('summary', () => {
    built.forEach(d => {
        const m = d.rows.map(r => r.misfit);
        // eslint-disable-next-line no-console
        console.log(`${d.key}: mean ${(m.reduce((a, b) => a + b) / m.length).toFixed(2)}°, max ${Math.max(...m).toFixed(2)}°`
            + `, misfits ${m.map(x => x.toFixed(1)).join(' ')}`);
    });
});
